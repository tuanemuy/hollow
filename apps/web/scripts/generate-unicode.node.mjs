import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const version = "16.0.0";
const base = new URL(
  "../../../packages/core/src/adapters/node/browse/",
  import.meta.url,
);
const manifest = JSON.parse(
  await readFile(new URL("unicode-sources.json", base), "utf8"),
);
if (manifest.version !== version)
  throw new Error("Unexpected Unicode manifest version");
if (
  manifest.license.id !== "Unicode-3.0" ||
  manifest.license.url !== "https://www.unicode.org/license.txt" ||
  manifest.license.file !== "UNICODE-LICENSE.txt"
)
  throw new Error("Unexpected Unicode license source");
async function get(name, source) {
  const response = await fetch(source.url, {
    signal: AbortSignal.timeout(15000),
  });
  if (!response.ok) throw new Error(`Unicode download failed: ${name}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (createHash("sha256").update(bytes).digest("hex") !== source.sha256) {
    throw new Error(`Unicode checksum mismatch: ${name}`);
  }
  return bytes.toString("utf8");
}
const [unicodeData, caseFolding, license] = await Promise.all([
  ...["UnicodeData.txt", "CaseFolding.txt"].map((name) => {
    const source = manifest.sources[name];
    if (
      source.url !== `https://www.unicode.org/Public/${version}/ucd/${name}`
    ) {
      throw new Error(`Unexpected Unicode source: ${name}`);
    }
    return get(name, source);
  }),
  get("license", manifest.license),
]);
if (!caseFolding.startsWith(`# CaseFolding-${version}.txt`))
  throw new Error("Unexpected case folding version");
const width = {};
const fold = {};
for (const line of unicodeData.split("\n")) {
  const fields = line.split(";");
  if (!/^<(wide|narrow)> /.test(fields[5] ?? "")) continue;
  width[fields[0]] = fields[5].replace(/^<[^>]+> /, "");
}
for (const line of caseFolding.split("\n")) {
  const [code, kind, mapping] = line.split(";").map((value) => value.trim());
  if (kind === "C" || kind === "F") fold[code] = mapping;
}
function mappingSource(mapping) {
  return `{\n${Object.entries(mapping)
    .map(([key, value]) => {
      const property = /^[A-F][0-9A-F]*$/.test(key) ? key : JSON.stringify(key);
      return `  ${property}: ${JSON.stringify(value)},`;
    })
    .join("\n")}\n}`;
}
const output = `// Generated by apps/web/scripts/generate-unicode.node.mjs.\n// Unicode ${version} data: Copyright © 2024 Unicode, Inc.\n// Unicode-3.0 license: UNICODE-LICENSE.txt; pinned sources: unicode-sources.json.\nexport const UNICODE_VERSION = ${JSON.stringify(version)};\nexport const WIDTH_MAPPING: Readonly<Record<string, string>> = ${mappingSource(width)};\nexport const FOLD_MAPPING: Readonly<Record<string, string>> = ${mappingSource(fold)};\n`;
await writeFile(new URL("unicodeData.ts", base), output);
await writeFile(new URL("UNICODE-LICENSE.txt", base), license);
